/// A managed coding agent running in a container.
/// Note: was "session" in the old TypeScript schema (migration 058 renamed it).
#[derive(Debug, Clone, Serialize, Deserialize, FromRow)]
pub struct Agent {
    pub id: AgentId,
    pub organization_id: OrgId,
    /// Workspace execution/access boundary. `project_id` is only the primary
    /// project context for routing and UI ownership.
    pub workspace_id: WorkspaceId,
    pub project_id: Option<ProjectId>,
    pub user_id: UserId,
    pub name: Option<String>,
    pub status: AgentStatus,
    pub container_id: Option<String>,
    /// Per-container HMAC-SHA256 key (issue #39). Generated by `start_agent`,
    /// injected into the sidecar as `HMAC_SECRET`, fetched by the
    /// orchestration result consumer to verify `SignedEnvelope` signatures.
    /// NEVER serialised — `#[serde(skip_serializing)]` keeps it out of every
    /// API response shape that re-uses this entity.
    #[serde(skip_serializing, default)]
    pub hmac_secret: Option<String>,
    /// Per-container NATS connect password (issue #38 phase 2). Generated by
    /// `start_agent`, embedded in the sidecar's `NATS_URL` as the user-info
    /// password, validated on CONNECT by the `services::auth_callout` service
    /// against the `user=<agent_uuid>` the sidecar presents. Cleared
    /// atomically with `hmac_secret` on `clear_container`. Deliberately stored
    /// separately from `hmac_secret` so a DB read of one secret does not also
    /// grant the other attacker surface (subject authorization vs. envelope
    /// forgery). NEVER serialised.
    #[serde(skip_serializing, default)]
    pub nats_connect_password: Option<String>,
    /// External CLI session identifier — NOT renamed per naming convention.
    pub cli_session_id: Option<String>,
    pub model: Option<String>,
    pub provider: Option<String>,
    /// CLI tool that runs inside this agent's container (`claude` / `codex` /
    /// `gemini` / `opencode`). NULL for provider+prompt agents that don't have
    /// a container shell. Used by `containers.rs` to pick the docker image.
    pub cli_tool: Option<String>,
    /// Provider+prompt agent identity (OpenAI Assistants `instructions` analogue).
    /// NULL for CLI-container agents.
    pub system_prompt: Option<String>,
    /// Working directory inside the container. NULL until the runtime reports it.
    pub cwd: Option<String>,
    /// Last tool the agent invoked — refreshed by the event pipeline.
    pub current_tool: Option<String>,
    /// Tokens consumed by the currently-active turn.
    pub tokens_current: i64,
    /// Lifetime token consumption.
    pub tokens_cumulative: i64,
    /// Compact git status hint ("clean", "+3 -1", "M wip/foo.rs").
    pub git_status: Option<String>,
    /// Sidecar/runtime identifier (e.g. "af-XXXXXXXX") — distinct from the DB PK.
    pub runtime_id: Option<String>,
    /// Cached MAX(events.created_at) so the admin list doesn't have to recompute it.
    pub last_activity_at: Option<DateTime<Utc>>,
    pub started_at: Option<DateTime<Utc>>,
    pub ended_at: Option<DateTime<Utc>>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

