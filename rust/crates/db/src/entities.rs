impl std::fmt::Debug for MemoryItem {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("MemoryItem")
            .field("id", &self.id)
            .field("organization_id", &self.organization_id)
            .field("workspace_id", &self.workspace_id)
            .field("owner_user_id", &self.owner_user_id)
            .field("scope_kind", &self.scope_kind)
            .field("scope_id", &self.scope_id)
            .field("source_task_id", &self.source_task_id)
            .field("source_run_id", &self.source_run_id)
            .field("title", &self.title)
            .field("content", &format_args!("<redacted; len={}>", self.content.len()))
            .field("content_redacted", &self.content_redacted)
            .field("content_encrypted", &self.content_encrypted)
            .field("visibility", &self.visibility)
            .field("sensitivity", &self.sensitivity)
            .field("provenance", &self.provenance)
            .field("ttl_expires_at", &self.ttl_expires_at)
            .field("confidence", &self.confidence)
            .field("last_used_at", &self.last_used_at)
            .field("last_verified_at", &self.last_verified_at)
            .field("state", &self.state)
            .field("revoked_at", &self.revoked_at)
            .field("created_at", &self.created_at)
            .field("updated_at", &self.updated_at)
            .finish()
    }
}

